/**
 * Safely escape output before displaying it in HTML.
 */
function verification_h($value)
{
    return htmlspecialchars((string) $value, ENT_QUOTES, 'UTF-8');
}

/**
 * Return a document URL only when the stored path is valid
 * and the document exists inside the uploaded-content folder.
 */
function verification_document_url($storedPath)
{
    if (empty($storedPath)) {
        return null;
    }

    $filename = basename(str_replace('\\', '/', $storedPath));

    // Only accept filenames generated by verification.php.
    if (!preg_match(
        '/^verification_[0-9]+_[a-f0-9]{32}\.(pdf|jpg|png)$/i',
        $filename
    )) {
        return null;
    }

    $uploadDirectory = realpath(__DIR__ . '/../uploaded-content');

    if ($uploadDirectory === false) {
        return null;
    }

    $filePath = realpath($uploadDirectory . DIRECTORY_SEPARATOR . $filename);

    // Confirm that the file exists and is inside the upload directory.
    if (
        $filePath === false ||
        dirname($filePath) !== $uploadDirectory ||
        !is_file($filePath)
    ) {
        return null;
    }

    return '../uploaded-content/' . rawurlencode($filename);
}

// Handle Approve and Reject form submissions.
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $csrfToken = $_POST['csrf_token'] ?? '';

    if (!eventnest_verify_csrf_token($csrfToken)) {
        auth_set_flash('Your session may have expired. Please try again.', 'error');
        auth_redirect('admin-panel/manage-verifications.php');
        exit;
    }

    $userId = filter_var(
        $_POST['user_id'] ?? null,
        FILTER_VALIDATE_INT
    );

    $decision = $_POST['decision'] ?? '';

    if (!$userId || !in_array($decision, ['verified', 'rejected'], true)) {
        auth_set_flash('Invalid verification request.', 'error');
        auth_redirect('admin-panel/manage-verifications.php');
        exit;
    }

    try {
        $sql = "
            UPDATE USERS
            SET VerificationStatus = :decision
            WHERE UserID = :user_id
              AND Role = 'organiser'
              AND VerificationStatus = 'pending'
              AND Verification_docs_path IS NOT NULL
              AND Verification_docs_path <> ''
        ";

        $stmt = $db->prepare($sql);

        $stmt->execute([
            ':decision' => $decision,
            ':user_id' => $userId
        ]);

        if ($stmt->rowCount() > 0) {
            if ($decision === 'verified') {
                auth_set_flash(
                    'The organiser has been approved successfully.',
                    'success'
                );
            } else {
                auth_set_flash(
                    'The organiser verification has been rejected.',
                    'success'
                );
            }
        } else {
            auth_set_flash(
                'No pending organiser verification was updated. It may already have been reviewed.',
                'error'
            );
        }
    } catch (PDOException $e) {
        error_log('Manage verifications error: ' . $e->getMessage());

        auth_set_flash(
            'Something went wrong while updating the verification. Please try again.',
            'error'
        );
    }

    auth_redirect('admin-panel/manage-verifications.php');
    exit;
}

